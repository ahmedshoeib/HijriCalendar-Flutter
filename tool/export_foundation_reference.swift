// Run from the package root on macOS:
// swift -module-cache-path /tmp/hijri-swift-cache tool/export_foundation_reference.swift
// This maintainer tool is never used by a consuming app.
import Foundation

let firstYear = 1299 // Padding permits complete six-week grids at the public edges.
let lastYear = 1601
let utc = TimeZone(secondsFromGMT: 0)!
var gregorian = Calendar(identifier: .gregorian)
gregorian.timeZone = utc
let epoch = gregorian.date(from: DateComponents(year: 1970, month: 1, day: 1))!
let systems: [(String, Calendar.Identifier)] = [
    ("ummAlQura", .islamicUmmAlQura), ("islamic", .islamic),
    ("civil", .islamicCivil), ("tabular", .islamicTabular)
]
var output = """
// Generated by tool/export_foundation_reference.swift. Do not edit by hand.
// Foundation reference: \(ProcessInfo.processInfo.operatingSystemVersionString).
// Public range: AH 1300...1600. Extra years are grid padding.

/// A calculation system, independent of language, time zone, and corrections.
enum HijriCalendarSystem { ummAlQura, islamic, civil, tabular }

const referenceFirstYear = \(firstYear);
const referenceLastYear = \(lastYear);
const referenceYearStarts = <HijriCalendarSystem, int>{
"""
var masks: [String: [Int]] = [:]
var fixtures: [[String: Any]] = []
for (name, identifier) in systems {
    var calendar = Calendar(identifier: identifier)
    calendar.timeZone = utc
    calendar.locale = Locale(identifier: "en_US_POSIX")
    func monthStart(_ year: Int, _ month: Int) -> Date {
        calendar.date(from: DateComponents(year: year, month: month, day: 1, hour: 12))!
    }
    func epochDay(_ date: Date) -> Int {
        gregorian.dateComponents([.day], from: epoch, to: gregorian.startOfDay(for: date)).day!
    }
    output += "\n  HijriCalendarSystem.\(name): \(epochDay(monthStart(firstYear, 1))),"
    var values: [Int] = []
    for year in firstYear...lastYear {
        var mask = 0
        for month in 1...12 {
            let next = month == 12 ? monthStart(year + 1, 1) : monthStart(year, month + 1)
            let days = gregorian.dateComponents([.day], from: monthStart(year, month), to: next).day!
            guard (29...30).contains(days) else { fatalError("Unsupported reference month \(name) \(year)-\(month): \(days)") }
            if days == 30 { mask |= 1 << (month - 1) }
        }
        values.append(mask)
    }
    masks[name] = values
    // Independent Gregorian-to-Hijri observations, sampled across the whole range.
    let start = epochDay(monthStart(1300, 1))
    let end = epochDay(monthStart(1601, 1))
    for day in stride(from: start, to: end, by: 97) {
        let instant = gregorian.date(byAdding: .day, value: day, to: epoch)!
        let h = calendar.dateComponents([.year, .month, .day], from: instant)
        fixtures.append(["system": name, "epochDay": day, "year": h.year!, "month": h.month!, "day": h.day!])
    }
    for year in [1300, 1400, 1447, 1448, 1500, 1600] {
        for month in 1...12 {
            let start = monthStart(year, month)
            fixtures.append(["system": name, "epochDay": epochDay(start), "year": year, "month": month, "day": 1])
        }
    }
}
output += "\n};\n\nconst referenceYearMasks = <HijriCalendarSystem, List<int>>{\n"
for (name, _) in systems {
    output += "  HijriCalendarSystem.\(name): [\n"
    let values = masks[name]!
    for offset in stride(from: 0, to: values.count, by: 12) {
        output += "    " + values[offset..<min(offset + 12, values.count)].map { String($0) }.joined(separator: ", ") + ",\n"
    }
    output += "  ],\n"
}
output += "};\n"
try output.write(toFile: "lib/src/core/calendar_data.dart", atomically: true, encoding: .utf8)
var fixtureSource = "// Generated independent Foundation observations. Do not edit.\n"
fixtureSource += "// Reference: \(ProcessInfo.processInfo.operatingSystemVersionString), UTC.\n"
fixtureSource += "const foundationSamples = <List<int>>[\n"
for sample in fixtures {
    let systemIndex = systems.firstIndex(where: { $0.0 == sample["system"] as! String })!
    fixtureSource += "  [\(systemIndex), \(sample["epochDay"]!), \(sample["year"]!), \(sample["month"]!), \(sample["day"]!)],\n"
}
fixtureSource += "];\n"
try fixtureSource.write(toFile: "test/fixtures/foundation_dates.dart", atomically: true, encoding: .utf8)
print("Generated four calendar datasets and \(fixtures.count) independent conversion samples.")
